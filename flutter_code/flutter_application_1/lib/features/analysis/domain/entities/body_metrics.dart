
class BodyMetrics {
  final int sleepHours;
  final double sleepChange;
  final int height;
  final double heightChange;
  final int weight;
  final double weightChange;
  final int heartRate;
  final double heartRateChange;
  final String bloodPressure;
  final double bloodPressureChange;

  BodyMetrics({
    required this.sleepHours,
    required this.sleepChange,
    required this.height,
    required this.heightChange,
    required this.weight,
    required this.weightChange,
    required this.heartRate,
    required this.heartRateChange,
    required this.bloodPressure,
    required this.bloodPressureChange,
  });
}
